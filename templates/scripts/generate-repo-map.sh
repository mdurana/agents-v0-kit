#!/bin/sh
# generate-repo-map.sh — produce docs/repo-map.md for agent retrieval (onboard-discovery).
# Usage: sh scripts/generate-repo-map.sh [repo-root]
set -eu
root="${1:-.}"
cd "$root"
out="docs/repo-map.md"
mkdir -p docs

PRUNE='-name node_modules -o -name target -o -name .git -o -name dist -o -name build -o -name .svelte-kit -o -name .next'

{
  printf '# Repository map\n\n'
  printf '> Generated by scripts/generate-repo-map.sh — refresh on onboard or major topology change.\n\n'

  printf '## Top-level layout\n\n```\n'
  # shellcheck disable=SC2086
  find . -maxdepth 3 \( $PRUNE \) -prune -o -type d -print 2>/dev/null | sort | head -n 80
  printf '```\n\n'

  printf '## Build entry points\n\n'
  [ -f pom.xml ] && printf -- '- Maven: `pom.xml`%s\n' "$([ -x ./mvnw ] && printf ' (wrapper `./mvnw`)')"
  [ -f build.gradle ] && printf -- '- Gradle: `build.gradle`\n'
  [ -f build.gradle.kts ] && printf -- '- Gradle: `build.gradle.kts`\n'
  [ -f package.json ] && printf -- '- Node: `package.json`\n'
  [ -f pnpm-workspace.yaml ] && printf -- '- pnpm workspace: `pnpm-workspace.yaml`\n'

  printf '\n## Modules\n\n'
  if [ -f pom.xml ]; then
    sed -n 's:.*<module>\(.*\)</module>.*:- Maven module `\1`:p' pom.xml
  fi
  for s in settings.gradle settings.gradle.kts; do
    [ -f "$s" ] && grep -Eo "include\(?[[:space:]]*['\"][^'\"]+['\"]" "$s" | sed -E "s/.*['\"]([^'\"]+)['\"]/- Gradle module \`\1\`/"
  done
  if [ -f package.json ] && grep -q '"workspaces"' package.json; then
    printf -- '- npm workspaces declared in `package.json`\n'
  fi

  printf '\n## Source roots (heuristic)\n\n'
  for d in src/main/java src/test/java src/main/resources src app lib packages; do
    [ -d "$d" ] && printf -- '- `%s`\n' "$d"
  done

  printf '\n## HTTP entry points\n\n'
  # shellcheck disable=SC2086
  find . \( $PRUNE \) -prune -o -name '*.java' -print 2>/dev/null \
    | xargs grep -l -E '@(RestController|Controller)\b' 2>/dev/null | sort | head -n 50 \
    | sed 's:^\./:- Controller `:; s:$:`:'
  # shellcheck disable=SC2086
  find . \( $PRUNE \) -prune -o -type f \( -name '+page.svelte' -o -name '+server.ts' -o -name '+page.server.ts' \) -print 2>/dev/null \
    | sort | head -n 50 | sed 's:^\./:- Route `:; s:$:`:'

  printf '\n## OpenAPI / contracts\n\n'
  # shellcheck disable=SC2086
  find . \( $PRUNE \) -prune -o \( -name 'api-v1.yaml' -o -name 'openapi*.yaml' -o -name 'openapi*.yml' -o -name 'openapi*.json' \) -print 2>/dev/null \
    | sort | head -n 20 | sed 's:^\./:- `:; s:$:`:'

  printf '\n## Architecture decisions\n\n'
  for d in docs/adr docs/decisions; do
    [ -d "$d" ] || continue
    for f in "$d"/*.md; do
      [ -f "$f" ] || continue
      title="$(grep -m1 '^# ' "$f" | sed 's/^# //')"
      printf -- '- `%s` — %s\n' "$f" "${title:-untitled}"
    done
  done

  printf '\n## Ownership\n\n'
  for c in CODEOWNERS .github/CODEOWNERS docs/CODEOWNERS; do
    [ -f "$c" ] || continue
    grep -Ev '^[[:space:]]*(#|$)' "$c" | head -n 40 | sed 's/^/- /'
  done
  printf '\n'
} >"$out"
printf 'Wrote %s\n' "$out"
