#!/bin/sh
# generate-repo-map.sh — produce docs/agents-v0/repo-map.md for agent retrieval (onboard-discovery).
# Usage: sh .agents-v0/scripts/generate-repo-map.sh [repo-root]
# Layout-aware: build files, modules, and source roots are read under every root that
# ci/resolve-layout.sh resolves (backend, bff, services, frontend; the repo root when none
# resolve). Every list is capped and says so when it is cut. The mechanical inventories
# (endpoints, entities, messaging, config) come from scripts/discover-codebase.sh.
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
root="${1:-.}"
cd "$root"
out="docs/agents-v0/repo-map.md"
mkdir -p docs

ROOTS=""
if [ -f "$here/../ci/resolve-layout.sh" ]; then
  eval "$(sh "$here/../ci/resolve-layout.sh")"
  ROOTS="${BACKEND_ROOT:-} ${BFF_ROOT:-} ${SERVICE_ROOTS:-} ${FRONTEND_ROOT:-}"
fi
ROOTS="$(printf '%s' "$ROOTS" | tr -s ' ' | sed 's/^ //;s/ $//')"
[ -n "$ROOTS" ] || ROOTS="."

PRUNE='-name node_modules -o -name target -o -name .git -o -name dist -o -name build -o -name .svelte-kit -o -name .next'

# cap <limit>: print the first <limit> lines of stdin, then say how many were cut.
cap() {
  awk -v limit="$1" 'NR <= limit { print } END { if (NR > limit) printf "TRUNCATED: showing %d of %d\n", limit, NR }'
}

{
  printf '# Repository map\n\n'
  printf '> Generated by scripts/generate-repo-map.sh — refresh on onboard or major topology change.\n\n'
  printf 'commit: %s\n\n' "$(git rev-parse HEAD 2>/dev/null || printf 'no-git')"

  printf '## Resolved roots\n\n'
  for r in $ROOTS; do printf -- '- `%s`\n' "$r"; done

  printf '\n## Top-level layout\n\n```\n'
  # shellcheck disable=SC2086
  find . -maxdepth 3 \( $PRUNE \) -prune -o -type d -print 2>/dev/null | sort | cap 200
  printf '```\n\n'

  printf '## Build entry points\n\n'
  for r in $ROOTS; do
    [ -f "$r/pom.xml" ] && printf -- '- Maven: `%s/pom.xml`%s\n' "$r" "$([ -x "$r/mvnw" ] && printf ' (wrapper `%s/mvnw`)' "$r")"
    [ -f "$r/build.gradle" ] && printf -- '- Gradle: `%s/build.gradle`\n' "$r"
    [ -f "$r/build.gradle.kts" ] && printf -- '- Gradle: `%s/build.gradle.kts`\n' "$r"
    [ -f "$r/package.json" ] && printf -- '- Node: `%s/package.json`\n' "$r"
    [ -f "$r/pnpm-workspace.yaml" ] && printf -- '- pnpm workspace: `%s/pnpm-workspace.yaml`\n' "$r"
  done
  [ -x ./mvnw ] && printf -- '- Maven wrapper at the repo root: `./mvnw`\n'

  printf '\n## Modules\n\n'
  for r in $ROOTS; do
    if [ -f "$r/pom.xml" ]; then
      grep -o '<module>[^<]*</module>' "$r/pom.xml" 2>/dev/null | sed 's:<module>\(.*\)</module>:\1:' | while IFS= read -r m; do
        printf -- '- Maven module `%s/%s`\n' "$r" "$m"
      done
    fi
    for s in settings.gradle settings.gradle.kts; do
      [ -f "$r/$s" ] && grep -Eo "include\(?[[:space:]]*['\"][^'\"]+['\"]" "$r/$s" | sed -E "s/.*['\"]([^'\"]+)['\"]/\1/" | while IFS= read -r m; do
        printf -- '- Gradle module `%s/%s`\n' "$r" "$m"
      done
    done
    if [ -f "$r/package.json" ] && grep -q '"workspaces"' "$r/package.json"; then
      printf -- '- npm workspaces declared in `%s/package.json`\n' "$r"
    fi
  done

  printf '\n## Source roots (heuristic)\n\n'
  for r in $ROOTS; do
    for d in src/main/java src/test/java src/main/resources src app lib packages; do
      [ -d "$r/$d" ] && printf -- '- `%s/%s`\n' "$r" "$d"
    done
  done

  printf '\n## HTTP entry points\n\n'
  # shellcheck disable=SC2086
  find . \( $PRUNE \) -prune -o -name '*.java' -print 2>/dev/null \
    | xargs grep -l -E '@(RestController|Controller)\b' 2>/dev/null | sort \
    | sed 's:^\./:- Controller `:; s:$:`:' | cap 200
  # shellcheck disable=SC2086
  find . \( $PRUNE \) -prune -o -type f \( -name '+page.svelte' -o -name '+server.ts' -o -name '+page.server.ts' \) -print 2>/dev/null \
    | sort | sed 's:^\./:- Route `:; s:$:`:' | cap 200
  printf '\nEndpoint-level rows (verb, path, annotation) and React routes: `docs/agents-v0/discovery/endpoints.txt`, `docs/agents-v0/discovery/frontend.txt`.\n'

  printf '\n## OpenAPI / contracts\n\n'
  # shellcheck disable=SC2086
  find . \( $PRUNE \) -prune -o \( -name 'api-v1.yaml' -o -name 'openapi*.yaml' -o -name 'openapi*.yml' -o -name 'openapi*.json' \) -print 2>/dev/null \
    | sort | sed 's:^\./:- `:; s:$:`:' | cap 100

  printf '\n## Architecture decisions\n\n'
  for d in docs/adr docs/decisions; do
    [ -d "$d" ] || continue
    for f in "$d"/*.md; do
      [ -f "$f" ] || continue
      title="$(grep -m1 '^# ' "$f" | sed 's/^# //')"
      printf -- '- `%s` — %s\n' "$f" "${title:-untitled}"
    done
  done

  printf '\n## Ownership\n\n'
  for c in CODEOWNERS .github/CODEOWNERS docs/CODEOWNERS; do
    [ -f "$c" ] || continue
    grep -Ev '^[[:space:]]*(#|$)' "$c" | sed 's/^/- /' | cap 100
  done
  printf '\n'
} >"$out"
printf 'Wrote %s\n' "$out"
