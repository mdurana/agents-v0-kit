#!/bin/sh
# discover-codebase.sh — mechanical inventories of an existing codebase for /v0-onboard.
#
# Usage: sh .agents-v0/scripts/discover-codebase.sh [repo-root]
# Scans the roots that ci/resolve-layout.sh resolves (backend, bff, services, frontend; the repo
# root when none resolve) and writes docs/agents-v0/discovery/:
#   endpoints.txt     HTTP endpoints with file:line and whether a security annotation is near.
#                     The scanner is ci/endpoint_scan.py, shared with check-endpoint-auth.sh.
#   entities.txt      ORM entities / models and their tables across packs
#   migrations.txt    Flyway / Liquibase / EF Core / Prisma / Alembic / SQL migration files
#   messaging.txt     Kafka / Rabbit / JMS / Stream / MassTransit / Celery / Go broker usage
#   scheduled.txt     Scheduled / background jobs (@Scheduled, BackgroundService, @Cron, Celery, time.NewTicker)
#   outbound.txt      HTTP client usage across packs (RestClient, HttpClient, fetch, axios, httpx, http.Client)
#   config.txt        configuration KEY NAMES, env references, secret-like keys (never values)
#   frontend.txt      SvelteKit / React routes, /api calls, public env names
#   ci-deploy.txt     Dockerfiles, compose, CI, Helm / Kubernetes / Terraform
#   tests.txt         test file counts per root
#   security-baseline.md  heuristic snapshot: unannotated endpoints, permit-all, literal secrets
#   endpoint-stacks.md    proposed dotnet / Nest / Express / FastAPI / Django / Go rows.
#                     Regexes are the BUILTINS table in ci/endpoint_scan.py.
#   baseline.md       measured tests / coverage / CVEs per backend root plus proposed ratchet rows
# Every list is capped (DISCOVER_MAX, default 500) and says so when it is cut. Rows are
# heuristics: read the cited line before relying on one. No secret value is ever printed.
# Needs python3. Refresh by running it again.

set -eu

here="$(cd "$(dirname "$0")" && pwd)"
root="${1:-.}"
cd "$root"

ROOTS=""
if [ -f "$here/resolve-layout.sh" ]; then
  eval "$(sh "$here/resolve-layout.sh")"
  ROOTS="${BACKEND_ROOT:-} ${BFF_ROOT:-} ${SERVICE_ROOTS:-} ${FRONTEND_ROOT:-}"
fi
ROOTS="$(printf '%s' "$ROOTS" | tr -s ' ' | sed 's/^ //;s/ $//')"
[ -n "$ROOTS" ] || ROOTS="."

command -v python3 >/dev/null 2>&1 || { printf 'FAIL: python3 is required\n' >&2; exit 1; }
COMMIT="$(git rev-parse HEAD 2>/dev/null || printf 'no-git')"

DISCOVER_ROOTS="$ROOTS" DISCOVER_COMMIT="$COMMIT" SCRIPTS_DIR="$here" python3 - <<'PY'
import json
import math
import os
import re
import subprocess
import sys

sys.path.insert(0, os.environ["SCRIPTS_DIR"])
import endpoint_scan
import packlib

ROOTS = os.environ["DISCOVER_ROOTS"].split()
COMMIT = os.environ["DISCOVER_COMMIT"]
GATE = ""
MAX = int(os.environ.get("DISCOVER_MAX") or 500)
OUT = os.path.join("docs", "agents-v0", "discovery")
SKIP = {"node_modules", "target", ".git", "dist", "build", ".svelte-kit", ".next", ".idea",
        ".gradle", "coverage", "docs", ".cursor", ".claude", ".kilo", "__pycache__"}
os.makedirs(OUT, exist_ok=True)
summary = []


def clip(text, n=160):
    text = text.strip()
    return text if len(text) <= n else text[: n - 3] + "..."


def read(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as handle:
            return handle.read().splitlines()
    except OSError:
        return []


def write(name, title, rows, note=""):
    lines = [f"# {title}", f"commit: {COMMIT}",
             "generated by scripts/discover-codebase.sh (heuristic scan; read the cited line before relying on a row)", ""]
    if note:
        lines += [note, ""]
    total = len(rows)
    lines += rows[:MAX]
    if total > MAX:
        lines.append(f"TRUNCATED: showing {MAX} of {total} (raise DISCOVER_MAX and re-run)")
    if total == 0:
        lines.append("(none found)")
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    summary.append((name, total, total > MAX))


# One walk over every resolved root.
files = []
seen = set()
for base in ROOTS:
    for dirpath, dirs, names in os.walk(base):
        dirs[:] = sorted(d for d in dirs if d not in SKIP)
        for name in sorted(names):
            rel = os.path.normpath(os.path.join(dirpath, name))
            if rel not in seen:
                seen.add(rel)
                files.append(rel)

java = [f for f in files if f.endswith(".java")]
text_of = {}


def lines_of(path):
    if path not in text_of:
        text_of[path] = read(path)
    return text_of[path]


# ---- Endpoints (shared scanners from ci/endpoint_scan.py) ------------------
endpoints, unannotated = [], []
active_pack = endpoint_scan.profile_pack()
active_stacks = endpoint_scan.profile_stacks()
all_specs = endpoint_scan.all_endpoint_specs()
for path in files:
    rows_for_file = []
    if active_pack or active_stacks:
        rows_for_file = list(endpoint_scan.scan_lines(path, lines_of(path), active_pack, active_stacks))
    else:
        if path.endswith(".java"):
            rows_for_file = list(endpoint_scan.java_endpoints(lines_of(path)))
        else:
            for spec in all_specs:
                if path.endswith(spec[0]):
                    rows_for_file.extend(endpoint_scan.extra_endpoints(lines_of(path), spec))
    for line_no, verb, full, secured in rows_for_file:
        row = f"{path}:{line_no}  {verb} {full}  {'annotated' if secured else 'NO-ANNOTATION'}"
        endpoints.append(row)
        if not secured:
            unannotated.append(row)
write("endpoints.txt", "HTTP endpoints", endpoints,
      "NO-ANNOTATION means no pack auth/public marker was found near the mapping; authorization may still be enforced in configuration or middleware.")

# ---- Entities, migrations --------------------------------------------------
entities = []
for path in files:
    if path.endswith(".java"):
        lines = lines_of(path)
        for i, ln in enumerate(lines):
            if re.search(r"@Entity\b", ln):
                nearby = lines[i: i + 12]
                cls = next((m.group(1) for l2 in nearby for m in [re.search(r"\bclass\s+(\w+)", l2)] if m), "?")
                tbl = next((m.group(1) for l2 in lines[max(0, i - 4): i + 5] for m in [re.search(r'@Table\([^)]*name\s*=\s*"([^"]+)"', l2)] if m), "")
                entities.append(f"{path}:{i + 1}  Entity {cls}" + (f"  table {tbl}" if tbl else ""))
    elif path.endswith(".cs"):
        for i, ln in enumerate(lines_of(path)):
            for m in re.finditer(r"DbSet<\s*(\w+)\s*>", ln):
                entities.append(f"{path}:{i + 1}  Entity {m.group(1)}")
    elif path.endswith(".py"):
        lines = lines_of(path)
        for i, ln in enumerate(lines):
            m = re.search(r"__tablename__\s*=\s*[\"']([^\"']+)[\"']", ln)
            if m:
                prev = lines[max(0, i - 8): i + 1]
                cls = next((c.group(1) for l2 in reversed(prev) for c in [re.search(r"\bclass\s+(\w+)", l2)] if c), "?")
                entities.append(f"{path}:{i + 1}  Entity {cls}  table {m.group(1)}")
    elif path.endswith(".ts"):
        lines = lines_of(path)
        for i, ln in enumerate(lines):
            if re.search(r"@Entity\b", ln):
                nearby = lines[i: i + 8]
                cls = next((m.group(1) for l2 in nearby for m in [re.search(r"\bclass\s+(\w+)", l2)] if m), "?")
                tbl = next((m.group(1) for m in [re.search(r"@Entity\(\s*[\"']([^\"']+)[\"']", ln)] if m), "")
                entities.append(f"{path}:{i + 1}  Entity {cls}" + (f"  table {tbl}" if tbl else ""))
    elif path.endswith(".go"):
        lines = lines_of(path)
        for i, ln in enumerate(lines):
            m = re.search(r"\btype\s+(\w+)\s+struct\b", ln)
            if m and any(re.search(r'`[^`]*\b(gorm|db):"[^"]+"', l2) for l2 in lines[i + 1: i + 20]):
                entities.append(f"{path}:{i + 1}  Entity {m.group(1)}")
write("entities.txt", "Persistent entities / models", entities)

migrations = [f for f in files if (("db/migration" in f.replace(os.sep, "/") and f.endswith(".sql"))
                                   or ("db/migrations" in f.replace(os.sep, "/") and f.endswith(".sql"))
                                   or "db/changelog" in f.replace(os.sep, "/")
                                   or "/alembic/versions/" in ("/" + f.replace(os.sep, "/"))
                                   or ("/migrations/" in ("/" + f.replace(os.sep, "/")).lower() and f.endswith((".sql", ".py", ".cs", ".ts", ".js")))
                                   or (re.search(r"changelog", os.path.basename(f), re.I) and f.endswith((".xml", ".yaml", ".yml", ".json"))))]
write("migrations.txt", "Database migrations", sorted(migrations),
      "Latest file by name is the last row of the sorted list.")


# ---- Pattern scans over backend code ---------------------------------------
code_files = [f for f in files if f.endswith((".java", ".cs", ".py", ".go", ".ts", ".js"))]


def scan(patterns, pool):
    regex = re.compile(patterns)
    rows = []
    for path in pool:
        for i, ln in enumerate(lines_of(path)):
            if regex.search(ln) and not ln.lstrip().startswith(("import ", "from ", "using ", "*", "//", "#")):
                rows.append(f"{path}:{i + 1}  {clip(ln)}")
    return rows


write("messaging.txt", "Messaging (listeners and producers)",
      scan(r"@(KafkaListener|RabbitListener|JmsListener|StreamListener|SqsListener|EnableKafka|EnableRabbit|MessagePattern|EventPattern)\b|"
           r"\b(KafkaTemplate|RabbitTemplate|StreamBridge|JmsTemplate|IBus|MassTransit|Confluent\.Kafka|"
           r"AIOKafkaConsumer|AIOKafkaProducer|kombu|bullmq|sarama|kafka\.NewReader|amqp\.Dial)\b|\bIConsumer<|\bCelery\(|\bsarama\.",
           code_files))
write("scheduled.txt", "Scheduled and async work",
      scan(r"@(Scheduled|Async|EnableScheduling|EnableAsync|SchedulerLock|Cron)\b|"
           r"\b(BackgroundService|IHostedService|Hangfire|RecurringJob|APScheduler|gocron|cron\.New)\b",
           code_files))
write("outbound.txt", "Outbound HTTP clients",
      scan(r"\b(RestTemplate|WebClient|RestClient|OkHttpClient|HttpClient|IHttpClientFactory|Refit|"
           r"httpx\.(?:AsyncClient|Client|get|post|put|delete)|requests\.(?:Session|get|post|put|delete)|"
           r"aiohttp\.ClientSession|axios\.(?:create|get|post|put|delete)|http\.NewRequest)\b|@FeignClient\b|@HttpExchange\b",
           code_files))

# ---- Configuration: key names only -----------------------------------------
CONFIG_FILE = re.compile(r"^(application|bootstrap)[\w.-]*\.(ya?ml|properties)$|^appsettings[\w.-]*\.json$|^\.env\.(example|sample|template)$")
SECRET_KEY = re.compile(r"(password|passwd|secret|token|api[-_.]?key|private[-_.]?key|credential)", re.I)
PLACEHOLDER_VAL = re.compile(
    r"^(changeme|change[-_]?me|todo|fixme|replace[-_]?me|placeholder|dummy|example|sample|none|null|nil|false|true|n/?a|xxx+|\*+|<[^>]+>|\{\{[^}]+\}\}|__[^_]+__)$",
    re.I,
)
keys, env_refs, secret_keys = [], [], []
for path in files:
    if not CONFIG_FILE.match(os.path.basename(path)):
        continue
    lines = read(path)
    is_yaml = path.endswith((".yml", ".yaml"))
    is_json = path.endswith(".json")
    stack = []
    for i, ln in enumerate(lines, 1):
        stripped = ln.strip()
        if not stripped or stripped.startswith(("#", "!", "- ", "{", "}", "[")) or stripped in ("},", "],"):
            continue
        for ref in re.findall(r"\$\{([A-Za-z0-9_.\-]+)", ln):
            env_refs.append(f"{path}:{i}  {ref}")
        if is_yaml or is_json:
            m = re.match(r'(\s*)["\']?([A-Za-z0-9_.\-]+)["\']?\s*:(.*)$', ln)
            if not m:
                continue
            indent, key, value = len(m.group(1)), m.group(2).strip("\"'"), m.group(3).strip().rstrip(",")
            if is_json and value in ("{", "["):
                value = ""
            while stack and stack[-1][0] >= indent:
                stack.pop()
            stack.append((indent, key))
            full = ".".join(k for _, k in stack)
        else:
            m = re.match(r"\s*([A-Za-z0-9_.\-\[\]]+)\s*[=:]\s*(.*)$", ln)
            if not m:
                continue
            full, value = m.group(1), m.group(2).strip()
        keys.append(f"{path}:{i}  {full}")
        if SECRET_KEY.search(full):
            clean_val = value.strip("\"'")
            if not clean_val:
                kind = "empty-or-nested"
            elif "${" in clean_val or clean_val.startswith("$"):
                kind = "env-ref"
            elif PLACEHOLDER_VAL.match(clean_val) or os.path.basename(path).startswith(".env."):
                kind = "placeholder"
            else:
                kind = "LITERAL-IN-FILE"
            secret_keys.append(f"{path}:{i}  {full}  ({kind})")
write("config.txt", "Configuration (key names only; values are never printed)",
      ["## keys"] + keys + ["", "## environment references"] + sorted(set(env_refs)) + ["", "## secret-like keys"] + secret_keys)

# ---- Frontend --------------------------------------------------------------
front_rows = []
for path in files:
    norm = path.replace(os.sep, "/")
    base = os.path.basename(path)
    if re.match(r"^\+(page|layout)(\.server)?\.(svelte|ts|js)$|^\+server\.(ts|js)$", base):
        route = norm.split("src/routes", 1)[1] if "src/routes" in norm else norm
        front_rows.append(f"{path}  SvelteKit route {os.path.dirname(route) or '/'}  ({base})")
    if path.endswith((".tsx", ".jsx", ".ts", ".js", ".svelte")):
        for i, ln in enumerate(lines_of(path), 1):
            for m in re.finditer(r"<Route\b[^>]*\bpath=\s*[\"']([^\"']+)", ln):
                front_rows.append(f"{path}:{i}  React route {m.group(1)}")
            if re.search(r"\b(createBrowserRouter|createRoutesFromElements|useRoutes)\b", ln):
                front_rows.append(f"{path}:{i}  React router setup")
            for m in re.finditer(r"[\"'`](/api/[^\"'`\s)]*)", ln):
                front_rows.append(f"{path}:{i}  API call {m.group(1)}")
            for m in re.finditer(r"\b(PUBLIC_[A-Z0-9_]+|VITE_[A-Z0-9_]+|NEXT_PUBLIC_[A-Z0-9_]+)\b", ln):
                front_rows.append(f"{path}:{i}  public env name {m.group(1)}")
write("frontend.txt", "Frontend routes, API calls, public env names", front_rows)

# ---- CI, container, deploy -------------------------------------------------
ci_rows = []
for dirpath, dirs, names in os.walk("."):
    dirs[:] = sorted(d for d in dirs if d not in SKIP - {"docs"} and d not in {"node_modules", "target", ".git", "dist", "build"})
    rel_dir = os.path.normpath(dirpath)
    for d in dirs:
        if d in {"k8s", "kubernetes", "helm", "charts", "terraform", "deploy", "deployment", "infra", "ops"}:
            ci_rows.append(os.path.normpath(os.path.join(rel_dir, d)) + "/")
    for name in sorted(names):
        rel = os.path.normpath(os.path.join(rel_dir, name))
        if (name.startswith("Dockerfile") or re.match(r"docker-compose.*\.ya?ml$", name)
                or name in {".gitlab-ci.yml", "Jenkinsfile", "Chart.yaml", "skaffold.yaml", "Makefile", "azure-pipelines.yml"}
                or name.endswith(".tf") or rel.replace(os.sep, "/").startswith(".github/workflows/")):
            ci_rows.append(rel)
write("ci-deploy.txt", "CI, container, and deploy files", ci_rows)

# ---- Tests -----------------------------------------------------------------
test_rows = []
pack_test_re = None
if active_pack:
    pdata = packlib.load(active_pack)
    if pdata and pdata.get("testFile"):
        try:
            pack_test_re = re.compile(pdata["testFile"])
        except re.error:
            pack_test_re = None
for base in ROOTS:
    prefix = "" if base == "." else base.rstrip("/") + os.sep
    inside = [f for f in files if f.startswith(prefix)]
    jtests = [f for f in inside if f.endswith(".java") and "/src/test/java/" in f.replace(os.sep, "/")]
    btests = [f for f in inside if re.search(r"(Test|Tests|IT)\.java$|Tests\.cs$|_test\.go$|(^|/)test_[^/]+\.py$", f.replace(os.sep, "/"))
              or (pack_test_re.search(f.replace(os.sep, "/")) if pack_test_re else False)]
    ftests = [f for f in inside if re.search(r"\.(test|spec)\.(js|ts|tsx|jsx|svelte)$", f)]
    e2e = [f for f in inside if re.match(r"^(playwright|cypress)\.config\.", os.path.basename(f))]
    extra = f"  backend test files {len(btests)}" if len(btests) != len(jtests) else ""
    test_rows.append(f"{base}  java test files {len(jtests)}{extra}  frontend test files {len(ftests)}  e2e config {len(e2e)}")
write("tests.txt", "Test files per root", test_rows)


# ---- Baseline numbers ------------------------------------------------------
def jvm(path):
    return any(os.path.isfile(os.path.join(path, f)) for f in ("pom.xml", "build.gradle", "build.gradle.kts"))


marker_set = set(packlib.marker_roots(".", 4))


def backend_root(path):
    norm = "." if path in ("", ".") else path.rstrip("/").replace(os.sep, "/")
    return jvm(path) or norm in marker_set or any(
        os.path.isfile(os.path.join(path, f)) for f in ("go.mod", "pyproject.toml", "Cargo.toml")
    )


base_rows, ratchet, failing = [], [], []
for base in ROOTS:
    if not backend_root(base):
        continue
    target = os.path.join(base, "target")
    if jvm(base) and not os.path.isdir(target):
        base_rows.append(f"| {base} | not measured: no target/ (run the baseline audit; Gradle builds are not read) | | | |")
        continue
    if GATE and os.path.isfile(GATE):
        env = dict(os.environ, GATE_REPORT_ONLY="1", ALLOW_NO_TESTS="1")
        subprocess.run(["sh", GATE, base], env=env, capture_output=True, text=True)
    summary_path = os.path.join(target, "gate-metrics.json")
    if not os.path.isfile(summary_path):
        alt = os.path.join(base, "gate-metrics.json")
        if os.path.isfile(alt):
            summary_path = alt
    data = None
    if os.path.isfile(summary_path):
        with open(summary_path, encoding="utf-8") as handle:
            data = json.load(handle)
    elif os.path.isdir(target):
        import xml.etree.ElementTree as ET
        run_c = fail_c = err_c = 0
        has_reports = False
        for rdir in (os.path.join(target, "surefire-reports"), os.path.join(target, "failsafe-reports")):
            if os.path.isdir(rdir):
                for fn in sorted(os.listdir(rdir)):
                    if fn.startswith("TEST-") and fn.endswith(".xml"):
                        has_reports = True
                        root_el = ET.parse(os.path.join(rdir, fn)).getroot()
                        for ts in ([root_el] if root_el.tag == "testsuite" else root_el.findall(".//testsuite")):
                            run_c += int(ts.attrib.get("tests", 0))
                            fail_c += int(ts.attrib.get("failures", 0))
                            err_c += int(ts.attrib.get("errors", 0))
        pct_val = None
        jacoco_xml = os.path.join(target, "site", "jacoco", "jacoco.xml")
        if os.path.isfile(jacoco_xml):
            has_reports = True
            root_el = ET.parse(jacoco_xml).getroot()
            for cnt in root_el.findall("./counter"):
                if cnt.attrib.get("type") == "LINE":
                    missed = int(cnt.attrib.get("missed", 0))
                    covered = int(cnt.attrib.get("covered", 0))
                    if missed + covered > 0:
                        pct_val = round(100.0 * covered / (missed + covered), 1)
        if has_reports:
            data = {"tests": {"run": run_c, "failures": fail_c, "errors": err_c}, "lineCoveragePct": pct_val, "highCriticalCves": None}
    if data is None:
        base_rows.append(f"| {base} | not measured: no gate-metrics summary | | | |")
        continue
    if not jvm(base) and data.get("failures") and (data.get("tests") or {}).get("run", 0) == 0 and data.get("lineCoveragePct") is None:
        base_rows.append(f"| {base} | not measured: no test/coverage reports (run the baseline audit) | | | |")
        continue
    tests = data.get("tests", {})
    pct = data.get("lineCoveragePct")
    cves = data.get("highCriticalCves")
    bad = int(tests.get("failures", 0)) + int(tests.get("errors", 0))
    base_rows.append(f"| {base} | {tests.get('run', 'n/a')} | {bad} | {'n/a' if pct is None else f'{pct}%'} | {'not scanned' if cves is None else len(cves)} |")
    if bad:
        failing.append(f"| {bad} | {base} | <owner> | <remove-by date> |")
    if pct is not None and pct < 80:
        ratchet.append(f"| {base} | {math.floor(pct)}% | <Security + architecture approver> | <remove-by date> |")

lines = ["# Baseline numbers", f"commit: {COMMIT}",
         "generated by scripts/discover-codebase.sh from build and test reports (read-only; nothing here is a gate)", "",
         "| Root | Tests run | Failures + errors | Bundle line coverage | Unsuppressed HIGH/CRITICAL CVEs |",
         "|------|-----------|-------------------|----------------------|----------------------------------|"]
lines += base_rows or ["| (no backend root) | | | | |"]
lines += ["", "## Proposed known_failures rows (for docs/agents-v0/project-profile.md; a person approves them)", "",
          "| Allowed failure count | Scope / test IDs | Owner | Remove by |",
          "|----------------------|------------------|-------|-----------|"] + (failing or ["| 0 | | | |"])
lines += ["", "## Proposed coverage_ratchet rows (Security + architecture approval required)", "",
          "| Scope | Interim minimum | Approver (Security + architecture) | Remove by |",
          "|-------|-----------------|------------------------------------|-----------|"] + (ratchet or ["| (none: every measured root meets 80%) | | | |"])
with open(os.path.join(OUT, "baseline.md"), "w", encoding="utf-8") as handle:
    handle.write("\n".join(lines) + "\n")
summary.append(("baseline.md", len(base_rows), False))

# ---- Security baseline snapshot --------------------------------------------
sec_patterns = re.compile(
    r"permitAll\(\)|permit-all|csrf\(\)\.disable|csrf\.disable|\.csrf\(.*disable|@EnableMethodSecurity|@EnableWebSecurity|"
    r"MethodSecurityBypass|authorizeHttpRequests|antMatchers|requestMatchers|@CrossOrigin|allowedOrigins\(\s*\"\*\"|"
    r"setAllowedOrigins|frameOptions\(\)\.(disable|sameOrigin)|"
    r"AllowAnonymous|DisableAntiforgery|AllowAnyOrigin|CORSMiddleware|enableCors|InsecureSkipVerify")
config_files = [f for f in files if CONFIG_FILE.match(os.path.basename(f))]
sec_rows = []
for path in list(dict.fromkeys(code_files + config_files)):
    for i, ln in enumerate(lines_of(path), 1):
        if sec_patterns.search(ln) and not ln.lstrip().startswith(("import ", "from ", "using ", "*", "//", "#")):
            key = ln.split(":", 1)[0].split("=", 1)[0]
            shown = clip(ln) if path in code_files or not SECRET_KEY.search(key) else clip(key)
            sec_rows.append(f"{path}:{i}  {shown}")
literal = [r for r in secret_keys if "LITERAL-IN-FILE" in r]
doc = ["# Security baseline snapshot", f"commit: {COMMIT}",
       "generated by scripts/discover-codebase.sh. Heuristics only: this is not a VAPT result and fixes nothing.",
       "Triage findings with /v0-maintain (Verify re-checks any fix that touches auth, sessions, routes, or uploads).", "",
       "## Endpoint authorization annotations", "",
       f"- Mappings found: {len(endpoints)}", f"- Without a nearby security annotation: {len(unannotated)}", ""]
doc += ["Unannotated mappings (first %d):" % min(len(unannotated), MAX), ""] + unannotated[:MAX]
